#!/usr/bin/env node
/* ============================================================
   schedule-vault.mjs
   The /schedule timetable is published encrypted so it can't be read
   from the page source or the public repo without the passcode.

   Edit the timetable:
     SCHEDULE_PIN=xxxx node tools/schedule-vault.mjs decrypt > /tmp/week.json
     (edit /tmp/week.json — keep it OUT of the repo)
     SCHEDULE_PIN=xxxx node tools/schedule-vault.mjs encrypt /tmp/week.json
   which rewrites schedule-vault.js. Changing the PIN = encrypt with a new one.

   Format of week.json:
     { "kinds": { "<id>": { "label": "...", "color": "#rrggbb", "routine"?: true } },
       "rest":  [6],                       // rest days, 0 = Monday … 6 = Sunday
       "week":  [ [ { "kind": "<id>", "start": "HH:MM", "end": "HH:MM", "flex"?: true } ], … 7 days ] }

   Crypto: PBKDF2-SHA256 (600k iterations, random salt) → AES-256-GCM.
   Must stay in step with unlock() in schedule.js.
   ============================================================ */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const ITERATIONS = 600000;
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'schedule-vault.js');
const { subtle } = globalThis.crypto;
const b64 = buf => Buffer.from(buf).toString('base64');
const unb64 = s => new Uint8Array(Buffer.from(s, 'base64'));

function pin() {
  const p = process.env.SCHEDULE_PIN || '';
  if (!/^\d{4,8}$/.test(p)) { console.error('Set SCHEDULE_PIN to the 4–8 digit passcode.'); process.exit(1); }
  return p;
}

async function keyFor(p, salt, iterations) {
  const base = await subtle.importKey('raw', new TextEncoder().encode(p), 'PBKDF2', false, ['deriveKey']);
  return subtle.deriveKey({ name: 'PBKDF2', hash: 'SHA-256', salt, iterations }, base, { name: 'AES-GCM', length: 256 }, false, ['encrypt', 'decrypt']);
}

function validate(data) {
  const ok = data && data.kinds && Array.isArray(data.week) && data.week.length === 7 && Array.isArray(data.rest);
  if (!ok) throw new Error('week.json needs kinds, rest and a 7-day week array');
  data.week.forEach((day, d) => day.forEach(e => {
    if (!data.kinds[e.kind]) throw new Error(`Day ${d}: unknown kind "${e.kind}"`);
    if (!/^\d\d:\d\d$/.test(e.start) || !/^\d\d:\d\d$/.test(e.end) || e.end <= e.start) throw new Error(`Day ${d}: bad time ${e.start}–${e.end}`);
  }));
}

async function encrypt(file) {
  const p = pin();
  const data = JSON.parse(readFileSync(file, 'utf8'));
  validate(data);
  const salt = crypto.getRandomValues(new Uint8Array(16));
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const key = await keyFor(p, salt, ITERATIONS);
  const ct = await subtle.encrypt({ name: 'AES-GCM', iv }, key, new TextEncoder().encode(JSON.stringify(data)));
  const vault = { v: 1, len: p.length, iter: ITERATIONS, salt: b64(salt), iv: b64(iv), data: b64(ct) };
  writeFileSync(OUT, `/* Encrypted timetable for /schedule. Generated by tools/schedule-vault.mjs — do not edit by hand. */\nwindow.SCHEDULE_VAULT = ${JSON.stringify(vault)};\n`);
  console.error(`Wrote ${OUT}`);
}

async function decrypt() {
  const p = pin();
  const src = readFileSync(OUT, 'utf8');
  const vault = JSON.parse(src.slice(src.indexOf('{'), src.lastIndexOf('}') + 1));
  const key = await keyFor(p, unb64(vault.salt), vault.iter);
  const pt = await subtle.decrypt({ name: 'AES-GCM', iv: unb64(vault.iv) }, key, unb64(vault.data));
  process.stdout.write(JSON.stringify(JSON.parse(new TextDecoder().decode(pt)), null, 2) + '\n');
}

const [cmd, arg] = process.argv.slice(2);
if (cmd === 'encrypt' && arg) await encrypt(arg);
else if (cmd === 'decrypt') await decrypt().catch(() => { console.error('Wrong passcode or damaged vault.'); process.exit(1); });
else { console.error('Usage: SCHEDULE_PIN=xxxx node tools/schedule-vault.mjs encrypt <week.json> | decrypt'); process.exit(1); }
